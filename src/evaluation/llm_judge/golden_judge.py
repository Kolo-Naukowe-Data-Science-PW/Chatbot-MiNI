"""
LLM-as-a-judge comparing a chatbot answer against a golden (supermodel) reference answer.

Key asymmetry handled by the judge
------------------------------------
- Chatbot answer: generated with RAG context (specific facts from the MiNI knowledge base).
- Golden answer: generated by a frontier model WITHOUT access to the knowledge base.
  It may openly admit "I don't have the exact schedule, but here's what I'd advise..."
  This honest acknowledgment of missing context is NOT penalised — it is the expected
  and correct behaviour for a model without RAG.

The judge evaluates whether the chatbot, *given* its retrieved context, produced an answer
that is at least as useful, accurate, and complete as what the supermodel would have said
if it had that context.
"""

import json
import logging
import os
import re
from typing import Literal

from dotenv import load_dotenv
from openai import OpenAI
from pydantic import BaseModel, Field, ValidationError

load_dotenv()

logger = logging.getLogger(__name__)


class GoldenJudgeScores(BaseModel):
    usefulness: int = Field(ge=1, le=5)
    accuracy: int = Field(ge=1, le=5)
    completeness: int = Field(ge=1, le=5)


class GoldenJudgeResult(BaseModel):
    chatbot: GoldenJudgeScores
    golden: GoldenJudgeScores
    better: Literal["chatbot", "golden"]
    chatbot_weaknesses: str
    golden_weaknesses: str


def build_golden_judge_prompt(
    query: str,
    chatbot_answer: str,
    golden_answer: str,
    language: str = "pl",
) -> list[dict[str, str]]:
    system_prompt = (
        "You are an expert evaluator comparing two answers to a university administrative chatbot query.\n\n"
        "ANSWER TYPES:\n"
        "- Chatbot answer: produced by a RAG system with access to a scraped knowledge base "
        "of the Faculty of Mathematics and Information Sciences (MiNI), Warsaw University of Technology. "
        "It may cite specific dates, procedures, or URLs from that knowledge base.\n"
        "- Golden answer: produced by a frontier AI model WITHOUT access to the knowledge base. "
        "It may openly say things like 'I don't have the current schedule, but generally...' or "
        "'You should check the faculty website for exact dates.' "
        "THIS IS CORRECT BEHAVIOUR — do NOT penalise the golden answer for admitting uncertainty "
        "or lack of specific data. Instead, evaluate whether its general guidance is sound.\n\n"
        "SCORING CRITERIA (1–5 integers):\n"
        "- Usefulness: how actionable and helpful is the answer for the student's actual need?\n"
        "  1 = useless or misleading  3 = partially helpful  5 = fully actionable\n"
        "- Accuracy: factual correctness given what each answer claims to know.\n"
        "  For the chatbot: penalise hallucinated specifics or wrong facts.\n"
        "  For the golden: honest uncertainty ('I'm not sure of the exact date') is NOT an error — "
        "score it on the correctness of what it does claim.\n"
        "  1 = major errors  3 = mostly correct with some issues  5 = fully correct\n"
        "- Completeness: does the answer cover the key aspects of the question?\n"
        "  1 = missing most of the answer  3 = covers the basics  5 = thorough\n\n"
        "OUTPUT: strictly valid JSON, no markdown, no extra text.\n"
        "Schema: {chatbot: {usefulness, accuracy, completeness}, "
        "golden: {usefulness, accuracy, completeness}, "
        "better: 'chatbot'|'golden', "
        "chatbot_weaknesses: '<one sentence>', "
        "golden_weaknesses: '<one sentence>'}\n"
        "For *_weaknesses: if the answer has no notable weaknesses, write 'Brak istotnych słabości.'"
    )

    user_prompt = (
        f"Language of the conversation: {language}\n\n"
        f"User query:\n{query}\n\n"
        f"--- Chatbot answer (has RAG context) ---\n{chatbot_answer}\n\n"
        f"--- Golden answer (no RAG context, may admit uncertainty) ---\n{golden_answer}\n\n"
        "Evaluate both answers according to the rubric above and output JSON now."
    )

    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]


def _extract_json(text: str) -> str:
    text = text.strip()
    if text.startswith("{") and text.endswith("}"):
        return text
    match = re.search(r"\{.*\}", text, flags=re.DOTALL)
    if not match:
        raise ValueError("No JSON object found in judge response")
    return match.group(0)


def parse_golden_judge_response(raw: str) -> GoldenJudgeResult:
    return GoldenJudgeResult(**json.loads(_extract_json(raw)))


def build_context_judge_prompt(
    query: str,
    chatbot_answer: str,
    golden_answer: str,
    language: str = "pl",
) -> list[dict[str, str]]:
    """Judge prompt for symmetric comparison: both answers had access to the knowledge base."""
    system_prompt = (
        "You are an expert evaluator comparing two answers to a university administrative chatbot query.\n\n"
        "CONTEXT: Both answers were produced with access to the same knowledge base "
        "(scraped documents from the Faculty of Mathematics and Information Sciences, MiNI, Warsaw University of Technology).\n"
        "- Chatbot answer: produced by a RAG pipeline.\n"
        "- Reference answer: produced by a frontier AI model with the full scraped text attached.\n\n"
        "SCORING CRITERIA (1–5 integers):\n"
        "- Usefulness: how actionable and helpful is the answer for the student's actual need?\n"
        "  1 = useless or misleading  3 = partially helpful  5 = fully actionable\n"
        "- Accuracy: factual correctness. Penalise hallucinations or contradictions with the knowledge base.\n"
        "  1 = major errors  3 = mostly correct with some issues  5 = fully correct\n"
        "- Completeness: does the answer cover the key aspects of the question?\n"
        "  1 = missing most of the answer  3 = covers the basics  5 = thorough\n\n"
        "OUTPUT: strictly valid JSON, no markdown, no extra text.\n"
        "Schema: {chatbot: {usefulness, accuracy, completeness}, "
        "golden: {usefulness, accuracy, completeness}, "
        "better: 'chatbot'|'golden', "
        "chatbot_weaknesses: '<one sentence>', "
        "golden_weaknesses: '<one sentence>'}\n"
        "For *_weaknesses: if the answer has no notable weaknesses, write 'Brak istotnych słabości.'"
    )

    user_prompt = (
        f"Language of the conversation: {language}\n\n"
        f"User query:\n{query}\n\n"
        f"--- Chatbot answer (RAG pipeline) ---\n{chatbot_answer}\n\n"
        f"--- Reference answer (supermodel with full context) ---\n{golden_answer}\n\n"
        "Evaluate both answers according to the rubric above and output JSON now."
    )

    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]


def judge_against_context_golden(
    query: str,
    chatbot_answer: str,
    golden_answer: str,
    *,
    judge_model: str,
    language: str = "pl",
    max_retries: int = 2,
) -> GoldenJudgeResult:
    """
    Symmetric comparison: both chatbot and reference answer had access to the knowledge base.

    Use this when golden answers were generated by a supermodel WITH the scraped text attached
    (e.g. via LM Studio / LM Notebooks), as opposed to judge_against_golden which handles
    the asymmetric case where the golden model had NO context.
    """
    api_key = os.getenv("OPENROUTER_API_KEY")
    if not api_key:
        raise RuntimeError("OPENROUTER_API_KEY is not set")

    client = OpenAI(base_url="https://openrouter.ai/api/v1", api_key=api_key)
    messages = build_context_judge_prompt(query, chatbot_answer, golden_answer, language)

    last_error: Exception | None = None
    for attempt in range(max_retries + 1):
        try:
            completion = client.chat.completions.create(
                model=judge_model,
                messages=messages,
                temperature=0.0,
                max_tokens=500,
                response_format={"type": "json_object"},
            )
            raw = completion.choices[0].message.content or ""
            return parse_golden_judge_response(raw)
        except (json.JSONDecodeError, ValidationError, ValueError) as exc:
            last_error = exc
            logger.warning("Judge parse failed (attempt %d/%d): %s", attempt + 1, max_retries + 1, exc)
        except Exception as exc:
            last_error = exc
            logger.warning("Judge API failed (attempt %d/%d): %s", attempt + 1, max_retries + 1, exc)

    raise RuntimeError(f"Context golden judge failed after retries: {last_error}")


def judge_against_golden(
    query: str,
    chatbot_answer: str,
    golden_answer: str,
    *,
    judge_model: str,
    language: str = "pl",
    max_retries: int = 2,
) -> GoldenJudgeResult:
    """
    Compare chatbot_answer against golden_answer using judge_model.

    Args:
        query: Original user question.
        chatbot_answer: Answer from the RAG chatbot.
        golden_answer: Reference answer from a supermodel (may acknowledge missing context).
        judge_model: OpenRouter model ID for the judge.
        language: Language hint passed to the judge prompt.
        max_retries: Extra attempts on parse/API failure.

    Raises:
        RuntimeError: If OPENROUTER_API_KEY is missing or all retries fail.
    """
    api_key = os.getenv("OPENROUTER_API_KEY")
    if not api_key:
        raise RuntimeError("OPENROUTER_API_KEY is not set")

    client = OpenAI(base_url="https://openrouter.ai/api/v1", api_key=api_key)
    messages = build_golden_judge_prompt(query, chatbot_answer, golden_answer, language)

    last_error: Exception | None = None
    for attempt in range(max_retries + 1):
        try:
            completion = client.chat.completions.create(
                model=judge_model,
                messages=messages,
                temperature=0.0,
                max_tokens=500,
                response_format={"type": "json_object"},
            )
            raw = completion.choices[0].message.content or ""
            return parse_golden_judge_response(raw)
        except (json.JSONDecodeError, ValidationError, ValueError) as exc:
            last_error = exc
            logger.warning("Judge parse failed (attempt %d/%d): %s", attempt + 1, max_retries + 1, exc)
        except Exception as exc:
            last_error = exc
            logger.warning("Judge API failed (attempt %d/%d): %s", attempt + 1, max_retries + 1, exc)

    raise RuntimeError(f"Golden judge failed after retries: {last_error}")
